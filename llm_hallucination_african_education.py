print("Loading model with attention outputs enabled...")

# AutoTokenizer converts text strings into token ID sequences
# A token is roughly a word or word-fragment the model understands
tokenizer = AutoTokenizer.from_pretrained('distilgpt2')

# AutoModelForCausalLM loads the actual transformer model
# output_attentions=True tells PyTorch to return attention matrices
# These matrices show which tokens the model "focuses on" at each layer
model = AutoModelForCausalLM.from_pretrained(
    'distilgpt2',
    output_attentions=True
)

# model.eval() sets the model to evaluation mode
# This disables dropout layers that are only used during training
model.eval()

def get_attention_for_question(question):
    # Format the question as a prompt (same format as generation)
    prompt = f"Question: {question}\nAnswer:"

    # tokenizer() converts our text into input_ids (integer token IDs)
    # return_tensors='pt' returns PyTorch tensors (needed by the model)
    inputs = tokenizer(prompt, return_tensors='pt')

    # torch.no_grad() disables gradient computation
    # We don't need gradients for inference — this saves memory and speed
    with torch.no_grad():
        outputs = model(**inputs)

    # outputs.attentions is a tuple of attention matrices — one per layer
    # We take the LAST layer [-1] as it captures the most abstract patterns
    # Shape: (batch_size, num_heads, seq_len, seq_len)
    attentions = outputs.attentions[-1]

    # We average across all attention heads (dim=0 after removing batch dim)
    # This gives us one attention matrix showing average focus patterns
    avg_attention = attentions[0].mean(dim=0)

    # Convert token IDs back to readable strings for axis labels
    tokens = tokenizer.convert_ids_to_tokens(inputs['input_ids'][0])

    return tokens, avg_attention

