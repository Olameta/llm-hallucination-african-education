# This function takes a question and returns the model's generated answer
def generate_answer(question, max_new_tokens=80):
    # We format the question as a prompt the model can respond to
    # This "Question: ... Answer:" format guides the model's output
    prompt = f"Question: {question}\nAnswer:"

    try:
        # We pass the prompt to the generator
        # max_new_tokens=80 limits how long the answer can be
        # num_return_sequences=1 means we only want one answer
        # temperature=0.7 controls randomness (0=deterministic, 1=very random)
        # do_sample=True enables sampling (needed when temperature != 1)
        # pad_token_id=50256 is GPT-2's end-of-sequence token
        result = generator(
            prompt,
            max_new_tokens=max_new_tokens,
            num_return_sequences=1,
            temperature=0.7,
            do_sample=True,
            pad_token_id=50256
        )

        # result[0]['generated_text'] contains the full prompt + answer
        full_text = result[0]['generated_text']

        # We split on "Answer:" and take everything after it
        # strip() removes leading and trailing whitespace
        answer = full_text.split("Answer:")[-1].strip()
        return answer

    except Exception as e:
        # If anything goes wrong, we return the error message
        # This prevents the whole loop from crashing on one bad question
        return f"ERROR: {str(e)}"

